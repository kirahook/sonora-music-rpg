export function letterFrontier(state){return Math.max(0,Math.min(companionLetters.length,Math.floor(Number(state?.frontier)||0)));}
export function readableLetterRegion(state,selected=0){const n=letterFrontier(state);return n===0?null:Number.isInteger(selected)&&selected>=0&&selected<n?selected:0;}
export function nextLetterIndex(region,index=0){const n=companionLetters[region]?.letters.length||0;return n?(Math.max(0,Math.floor(Number(index)||0))+1)%n:0;}
