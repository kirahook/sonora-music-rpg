export function atlasCards(index,albums){
 const atlas=regionAtlas[index];if(!atlas)return [];
 const records=atlas.records.map(code=>albums.find(a=>a.code===code)).filter(Boolean);
 return [
  ...records.map(a=>({id:a.code,type:'album',label:'代表专辑',title:a.title,subtitle:`${a.artist} · ${a.year}`,body:a.note,album:a.code,cover:a.cover,source:['Apple Music · 专辑资料',a.source]})),
  ...records.map(a=>({id:`${a.code}-artist`,type:'artist',label:'音乐家索引',title:a.artist,subtitle:'从一张唱片认识创作者',body:`本海域推荐入口：《${a.title}》（${a.year}）。${a.note} 先记住一种喜欢的音色，再沿着唱片资料认识创作者与参与者。`,album:a.code,source:['Apple Music · 作品与参与者',a.source]})),
  ...atlas.concepts.map(c=>({...c,type:'concept',label:'听觉索引',subtitle:'没有标准答案的聆听练习',album:atlas.records[0],source:atlas.sources[0]})),
 ];
}
